const DICTIONARIES: Record<Locale, Partial<Record<TranslationKey, string>>> = { en, ar, fr }

// ---------------------------------------------------------------------------
// Locale persistence + store
// ---------------------------------------------------------------------------

async function readStoredLocale(): Promise<Locale | null> {
  try {
    const raw = Platform.OS === 'web'
      ? localStorage.getItem(STORAGE_KEY)
      : await SecureStore.getItemAsync(STORAGE_KEY)
    return raw === 'en' || raw === 'ar' || raw === 'fr' ? raw : null
  } catch {
    return null
  }
}

function writeStoredLocale(locale: Locale): void {
  try {
    if (Platform.OS === 'web') localStorage.setItem(STORAGE_KEY, locale)
    else void SecureStore.setItemAsync(STORAGE_KEY, locale)
  } catch {
    // Non-fatal — locale just won't persist
  }
}

function deviceLocale(): Locale {
  const lang = Localization.getLocales()[0]?.languageCode
  return lang === 'ar' || lang === 'fr' ? lang : 'en'
}

export const isRTL = (locale: Locale): boolean => locale === 'ar'

// Web flips the whole document immediately; native goes through I18nManager,
// whose direction change only applies on the next app launch (RN snapshot
// behaviour) — until then translated strings render in an LTR frame.
function applyLayoutDirection(locale: Locale): void {
  const rtl = isRTL(locale)
  if (Platform.OS === 'web') {
    try { document.documentElement.dir = rtl ? 'rtl' : 'ltr' } catch {
      // SSR / no DOM — nothing to flip
    }
    return
  }
  I18nManager.allowRTL(rtl)
  if (I18nManager.isRTL !== rtl) {
    I18nManager.forceRTL(rtl)
  }
}

interface LocaleState {
  locale: Locale
  setLocale: (l: Locale) => void
}

export const useLocaleStore = create<LocaleState>((set) => ({
  locale: deviceLocale(),
  setLocale: (locale) => {
    writeStoredLocale(locale)
    applyLayoutDirection(locale)
    set({ locale })
  },
}))

applyLayoutDirection(useLocaleStore.getState().locale)

// Stored preference beats device default — applied once at import time
void readStoredLocale().then(stored => {
  if (stored) {
    applyLayoutDirection(stored)
    useLocaleStore.setState({ locale: stored })
  }
})

// ---------------------------------------------------------------------------
// Translation
// ---------------------------------------------------------------------------

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  let text = DICTIONARIES[locale][key] ?? en[key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}

// Hook — subscribes to locale changes so screens re-render on switch
export function useT() {
  const locale = useLocaleStore(s => s.locale)
  return (key: TranslationKey, vars?: Record<string, string | number>) =>
    translate(locale, key, vars)
}
